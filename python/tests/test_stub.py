"""Stub-binary tests: the shim drives a fake `aegis` executable.

Cross-platform stub design: one python payload script does the work
(argv logging, stdout JSON, stderr text, exit code); the executable the
shim resolves is a small launcher on top of it — `aegis.cmd` invoking
python on win32, a shebang `aegis` script on POSIX.
"""

from __future__ import annotations

import json
import os
import shutil
import stat
import sys
from pathlib import Path

import pytest

import aegis
from aegis import AegisEngineError

STUB_REPORT_OK = {
    "id": "stub-job",
    "ok": True,
    "exit_reason": "ok",
    "prompt": "p",
    "output": "o",
    "claims": [
        {
            "id": "c0",
            "text": "o",
            "stance": "asserted",
            "grounding": "supported",
            "grounding_reason": "",
            "evidence": [],
        }
    ],
    "steps": [],
    "critique": {"verdict": "agree", "notes": "", "disputed_claim_ids": []},
    "code_checks": [],
    "failed_assertions": [],
    "warnings": [],
    "cache": {"hit": False, "key": "0" * 64},
}


def make_stub(
    tmp_path: Path,
    *,
    report: dict | None = None,  # printed to stdout when set
    exit_code: int = 0,
    stderr: str = "",
    snapshot_job: str | None = None,  # copy argv job file here
) -> str:
    """Create a working fake `aegis` binary in tmp_path; return its path.

    The payload records every invocation's argv into aegis-calls.jsonl
    next to the payload so tests can assert on the CLI contract.
    """
    payload = tmp_path / "aegis-payload.py"
    # The report/stage payloads must be embedded as PYTHON literals, not
    # JSON: json.dumps emits `true`/`false`, valid JSON but invalid
    # Python — the payload crashed with NameError: true before the
    # report ever printed. repr() is the safe serializer here.
    payload.write_text(
        (
            "# stub aegis payload generated by tests\n"
            "import json, sys\n"
            f"payload_report = {report!r}\n"
            f"payload_exit = {int(exit_code)}\n"
            f"payload_stderr = {stderr!r}\n"
            f"payload_snapshot = {snapshot_job!r}\n"
            "with open(__file__ + '.calls.jsonl', 'a') as f:\n"
            "    f.write(json.dumps(sys.argv[1:]) + chr(10))\n"
            "if payload_snapshot is not None:\n"
            "    with open(sys.argv[2], encoding='utf-8') as jf:\n"
            "        open(payload_snapshot, 'w', encoding='utf-8').write(jf.read())\n"
            "if payload_stderr:\n"
            "    print(payload_stderr, file=sys.stderr, end='')\n"
            "if payload_report is not None:\n"
            "    print(json.dumps(payload_report))\n"
            "sys.exit(payload_exit)\n"
        ),
        encoding="utf-8",
    )

    if sys.platform == "win32":
        launcher = tmp_path / "aegis.cmd"
        launcher.write_text(
            f'\n@echo off\n"{sys.executable}" "%~dp0aegis-payload.py" %*\n',
            encoding="utf-8",
        )
    else:
        launcher = tmp_path / "aegis"
        launcher.write_text(
            f"#!/bin/sh\nexec {sys.executable} {payload} \"$@\"\n",
            encoding="utf-8",
        )
    st = os.stat(launcher)
    os.chmod(launcher, st.st_mode | stat.S_IEXEC)
    return str(launcher)


def read_calls(tmp_path: Path) -> list[list[str]]:
    calls = tmp_path / "aegis-payload.py.calls.jsonl"
    assert calls.exists(), "stub was never invoked"
    return [json.loads(line) for line in calls.read_text(encoding="utf-8").splitlines() if line.strip()]


def test_verify_ok_with_stub(tmp_path, monkeypatch):
    monkeypatch.setenv("AEGIS_BINARY", make_stub(tmp_path, report=STUB_REPORT_OK))
    r = aegis.verify(prompt="p", output="o", must_claim=["o"])
    assert r.ok is True
    assert r.id == "stub-job"
    argv0 = read_calls(tmp_path)[0]
    assert argv0[0] == "run" and argv0[1].endswith(".yaml")  # verify default is YAML (a JSON subset)


def test_job_kwargs_reach_the_file(tmp_path, monkeypatch):
    # verify() deletes its temp job file on return, so the test reads it
    # via the stub instead: the payload snapshots job bytes into a stable
    # path under tmp_path before verify() can unlink it.
    snapshot = tmp_path / "last-job.json"
    rep = dict(STUB_REPORT_OK)
    monkeypatch.setenv("AEGIS_BINARY", make_stub(tmp_path, report=rep, snapshot_job=str(snapshot)))
    r = aegis.verify(prompt="p", output="o", must_claim=["cache key"], grounded=True)
    job = json.loads(snapshot.read_text(encoding="utf-8"))
    assert job["assertions"]["must_claim"] == ["cache key"]
    assert job["assertions"]["grounded"] is True
    assert r.ok


def test_verify_report_exit1(tmp_path, monkeypatch):
    rep = dict(STUB_REPORT_OK)
    rep.update(ok=False, exit_reason="assertions_failed",
               failed_assertions=[{"type": "must_claim", "expected": "x", "actual": "", "detail": ""}])
    monkeypatch.setenv("AEGIS_BINARY", make_stub(tmp_path, report=rep))
    r = aegis.verify(prompt="p", output="o")
    assert r.ok is False
    assert r.failed_assertions[0].type == "must_claim"


def test_engine_error_matches_d2_prefix(tmp_path, monkeypatch):
    monkeypatch.setenv(
        "AEGIS_BINARY",
        make_stub(tmp_path, exit_code=2, stderr="error: missing-env: USER_LLM_API_KEY\n"),
    )
    with pytest.raises(AegisEngineError) as ei:
        aegis.verify(prompt="p", output="o", cache_only=True)
    assert ei.value.kind == "missing-env"
    assert "USER_LLM_API_KEY" in str(ei.value)


def test_no_cache_flag_forwarded(tmp_path, monkeypatch):
    monkeypatch.setenv("AEGIS_BINARY", make_stub(tmp_path, report=STUB_REPORT_OK))
    aegis.verify(prompt="p", output="o", no_cache=True, cache_dir="cd")
    args = read_calls(tmp_path)[0]
    assert "--no-cache" in args and "--cache-dir" in args


def test_raise_on_fail_inlines_assertions(tmp_path, monkeypatch):
    rep = dict(STUB_REPORT_OK)
    rep.update(
        ok=False,
        exit_reason="assertions_failed",
        claims=[
            {"id": "c0", "text": "stored in git", "stance": "asserted",
             "grounding": "contradicted", "grounding_reason": "", "evidence": []}
        ],
        failed_assertions=[
            {"type": "grounded", "expected": "supported", "actual": "contradicted", "detail": ""}
        ],
    )
    monkeypatch.setenv("AEGIS_BINARY", make_stub(tmp_path, report=rep))
    with pytest.raises(AssertionError) as ei:
        aegis.verify(prompt="p", output="o", raise_on_fail=True)
    msg = str(ei.value)
    assert "grounded" in msg and "stored in git" in msg  # disagreeing claim inlined


def test_missing_binary_is_friendly(monkeypatch):
    monkeypatch.delenv("AEGIS_BINARY", raising=False)
    monkeypatch.setattr(shutil, "which", lambda n: None)
    with pytest.raises(FileNotFoundError):
        aegis.verify(prompt="p", output="o")


def test_runner_timeout_expired(tmp_path, monkeypatch):
    monkeypatch.setenv("AEGIS_BINARY", make_stub(tmp_path, report=STUB_REPORT_OK))
    import subprocess
    def fake_run(*args, **kwargs):
        raise subprocess.TimeoutExpired(cmd=["aegis"], timeout=0.1)
    monkeypatch.setattr(subprocess, "run", fake_run)
    with pytest.raises(AegisEngineError) as ei:
        aegis.verify(prompt="p", output="o", timeout=0.1)
    assert ei.value.kind == "run-timeout"

